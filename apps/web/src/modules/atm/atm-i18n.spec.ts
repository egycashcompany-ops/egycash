describe('atm i18n catalog', () => {
  it.each(LOCALES)('every ATM key resolves in %s', (locale) => {
    const missing = KEYS.filter((key) => translate(locale, key) === key);
    expect(missing).toEqual([]);
  });

  it.each(LOCALES)('every mail status label resolves in %s', (locale) => {
    const missing = ATM_MAIL_TICKET_STATUSES.map((status) => `atm.mail.status.${status}`).filter(
      (key) => translate(locale, key) === key,
    );
    expect(missing).toEqual([]);
  });

  it.each(LOCALES)('every overview card resolves in %s', (locale) => {
    const missing = ATM_SHORTCUTS.flatMap((shortcut) => [
      shortcut.titleKey,
      shortcut.descKey,
    ]).filter((key) => translate(locale, key) === key);
    expect(missing).toEqual([]);
  });
});
